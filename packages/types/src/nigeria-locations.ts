export const NIGERIA_STATES: readonly string[] = Object.keys(NIGERIA_LOCATIONS)

export function lgasForState(state: string): readonly string[] {
  return NIGERIA_LOCATIONS[state] ?? []
}

/** What every address form collects. Plain strings, so it works with `useState` and
 *  react-hook-form alike; `landmark` is the only optional one. */
export interface AddressValue {
  street: string
  city: string
  state: string
  lga: string
  landmark: string
}

export const EMPTY_ADDRESS: AddressValue = { street: '', city: '', state: '', lga: '', landmark: '' }

export function addressFromApi(
  src:
    | {
        street?: string | null
        city?: string | null
        state?: string | null
        lga?: string | null
        landmark?: string | null
      }
    | null
    | undefined,
): AddressValue {
  return {
    street: src?.street ?? '',
    city: src?.city ?? '',
    state: src?.state ?? '',
    lga: src?.lga ?? '',
    landmark: src?.landmark ?? '',
  }
}

/** Why the address can't be saved yet, or null. With `requireAll: false` an entirely blank
 *  address is fine (nothing is being set) but a half-filled one is not. */
export function addressProblem(v: AddressValue, { requireAll }: { requireAll: boolean }): string | null {
  const touched = Object.values(v).some((x) => x.trim() !== '')
  if (!touched && !requireAll) return null
  if (!v.street.trim()) return 'Enter the street number and name.'
  if (!v.city.trim()) return 'Enter the town or city.'
  if (!v.state) return 'Select a state.'
  if (!v.lga) return 'Select a local government area.'
  return null
}

/** `Sango Ota, Ogun State` — where a vendor is, in the words customers use. Null when unknown. */
export function formatVendorLocation(city?: string | null, state?: string | null): string | null {
  const place = city?.trim()
  const region = state ? (state === 'FCT' ? 'FCT' : `${state} State`) : null
  return [place, region].filter(Boolean).join(', ') || null
}
